    def validate_params(self, params, *, warn: bool = True):
        """
        parameter validation for the PV model. Checks for required parameters, types, value ranges and cross-field logic.
        """
        name = type(self).__name__
        hard_errors = []
        
        rules = {
            # required for these models
            "calc_mode": {
                "required": True,
                "types": (str),
                "pred": lambda v: v in ["simple"],
                "msg": "unsupported 'calc_mode'. Supported modes: 'simple'",
            },
            "nom_power": {
                "required": True,
                "types": (int, float, np.number),
                "pred": lambda v: v > 0,
                "msg": "'nom_power' must be a number > 0 when provided.",
            },
            "coordinates": {
                "required": True,
                "types": (list, tuple),
                "pred": lambda v: len(v) == 5 and isinstance(v[0], (int, float)) and isinstance(v[1], (int, float)) and isinstance(v[2], str) and isinstance(v[3], (int, float)) and isinstance(v[4], str),
                "msg": "'coordinates' must be a list/tuple of 5 values [latitude, longitude, name, altitude, timezone] for eg. [49.1, 8.5, 'Karlsruhe', 110, 'Etc/GMT-1'].",
            },
            "op_year": {
                "required": True,
                "types": (int),
                "pred": lambda v: v > 0,
                "msg": "'op_year' must be a positive integer."
            },
            "op_mode": {
                "required": True,
                "types": (str),
                "pred": lambda v: v in ["standalone", "mosaik"],
                "msg": "'op_mode' must be either 'standalone' or 'mosaik'. mosaik mode is currently a work in progress so please use 'standalone' for now."
            },

            # optional parameters 
            "irradiation_data": {
                "required": False,
                "types": (str),
                "pred": lambda v: v.strip() != "",
                "msg": "'irradiation_data' must be a non-empty string with a relative path to the weather CSV from the project root.",
            },
            "surface_tilt": {
                "required": False,
                "types": (int, float, np.number),
                "pred": lambda v: 0 <= v <= 360,
                "msg": "'surface_tilt' must be a number between 0 and 360 degrees.",
            },
            "surface_azimuth": {
                "required": False,
                "types": (int, float, np.number),
                "pred": lambda v: 0 <= v < 360,
                "msg": "'surface_azimuth' must be a number between 0 and less than 360 degrees.",
            },
            "pv_arrays": {
                "required": False,
                "types": (list,),
                "pred": lambda v: all(isinstance(arr, dict) and 'tilt'
                    in arr and 'azimuth' in arr and isinstance(arr['tilt'], (int, float)) and isinstance(arr['azimuth'], (int, float)) for arr in v),
                "msg": "'pv_arrays' must be a list of dicts with 'tilt' and 'azimuth' as numbers, e.g. [{'tilt': 30, 'azimuth': 270}, {'tilt': 30, 'azimuth': 90}]."
            }
        }

        for key, rule in rules.items():
            required = rule.get("required", False)
            types_ = rule.get("types", None)
            pred = rule.get("pred", None)
            msg = rule.get("msg", f"Invalid '{key}'.")

            if key not in params:
                if required:
                    hard_errors.append(f"{name}: missing required parameter '{key}'.")
                continue

            val = params.get(key, None)
            if val is None:
                if required:
                    hard_errors.append(f"{name}: parameter '{key}' must not be None.")
                continue

            if types_ is not None and not isinstance(val, types_):
                hard_errors.append(f"{name}: {msg}")
                continue

            if pred is not None and not pred(val):
                hard_errors.append(f"{name}: {msg}")
        # -------------------- cross-field required logic --------------------
        expected_year = pd.Timestamp(params["sim_start"]).year
        if params["op_year"] != expected_year:
            hard_errors.append(f"{name}: op_year must match START year in main_sim ({expected_year}).")

        if hard_errors:
            raise ValueError(
                f"{name} configuration error(s):\n- " + "\n- ".join(hard_errors)
            )
